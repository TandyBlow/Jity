def main():
    world = json.loads(WORLD.read_text(encoding='utf8'))['initial']
    goals = {tid: task['goal'] for c in world['characters'].values() for tid, task in c['tasks'].items()}
    owners = {tid: cid for cid, c in world['characters'].items() for tid in c['tasks']}
    rows = []
    for tid, yes, partial, no in PAIRS:
        if tid not in goals:
            raise SystemExit(f'unknown task {tid}')
        for fact, label in ((yes, 'yes'), (partial, 'partial'), (no, 'no')):
            rows.append({'task_id': tid, 'actor': owners[tid], 'goal': goals[tid], 'fact': fact,
                         'relevance': 1, 'satisfaction': label})
    for tid, fact in UNRELATED:
        rows.append({'task_id': tid, 'actor': owners[tid], 'goal': goals[tid], 'fact': fact,
                     'relevance': 0, 'satisfaction': 'no'})
    tasks = sorted({row['task_id'] for row in rows})
    held = set(tasks[::4])
    for row in rows:
        row['split'] = 'test' if row['task_id'] in held else 'train'
    (PUB / 'task-match-data.jsonl').write_text(
        ''.join(json.dumps(row, ensure_ascii=False) + '\n' for row in rows), encoding='utf8')
    print('rows', len(rows), 'tasks', len(tasks), 'held', sorted(held))
    print('labels', {k: dict(Counter(row[k] for row in rows)) for k in ('relevance', 'satisfaction')})


if __name__ == '__main__':
    main()
