// Register the static world asset's digests for the product loader.
//
// The page must not start a game from a file that merely parses. This script
// reads the committed asset, runs the same loader the page runs, and writes the
// registration the loader verifies against:
//
//   stateDigest    world-canonical-v1 SHA-256 of the static WorldState
//   fileSha256Lf   SHA-256 of the UTF-8 text after CRLF/CR -> LF
//   initialDigest  world-canonical-v1 SHA-256 of `initial`
//
//   node scripts/product/register-static-world.mjs [--world public/worlds/x.json]
//
// Re-run when the world asset changes; the diff is the registration change.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const here = dirname(fileURLToPath(import.meta.url));
const frontend = resolve(here, '../..');
const flag = (name, fallback) => {
  const index = process.argv.indexOf(name);
  return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
};
const worldRelative = flag('--world', 'public/worlds/dragon-raja-free-day.world.json');
const worldPath = resolve(frontend, worldRelative);
const text = readFileSync(worldPath, 'utf8');

const server = await createServer({ root: frontend, configFile: false, logLevel: 'error', server: { middlewareMode: true } });
try {
  const { loadStaticWorld } = await server.ssrLoadModule('/src/lib/world-engine/local/world-loader.ts');
  // First pass computes the digests; the loader needs a registration, so hand
  // it the values this same read produces in a second pass.
  const { parseStaticWorldJson, readStaticWorldValue, normalizeWorldText } =
    await server.ssrLoadModule('/src/lib/world-engine/local/world-loader.ts');
  const { canonicalDigest } = await server.ssrLoadModule('/src/lib/world-engine/local/canonical.ts');
  const { stateDigest } = await server.ssrLoadModule('/src/lib/world-engine/local/state.ts');
  const normalized = normalizeWorldText(text);
  const parsed = parseStaticWorldJson(text);
  const read = readStaticWorldValue(parsed);
  const { createHash } = await import('node:crypto');
  const digests = {
    stateDigest: await stateDigest(read.state),
    fileSha256Lf: createHash('sha256').update(normalized, 'utf8').digest('hex'),
    initialDigest: await canonicalDigest(read.initial),
  };
  const loaded = await loadStaticWorld(text, { stateDigest: digests.stateDigest, fileSha256Lf: digests.fileSha256Lf, initialDigest: digests.initialDigest });
  const out = resolve(frontend, 'src/lib/world-engine/local/static-world-registration.ts');
  writeFileSync(out, `/** Generated by scripts/product/register-static-world.mjs. Do not edit by hand.
 *
 * Asset: ${worldRelative}
 * Registered: stateDigest (world-canonical-v1), LF-normalized file hash and
 * initial digest. The product page refuses to start when any of them differ.
 */
export const STATIC_WORLD_ASSET = '${worldRelative.replace('public', '')}';

export const STATIC_WORLD_REGISTRATION = {
  stateDigest: '${digests.stateDigest}',
  fileSha256Lf: '${digests.fileSha256Lf}',
  initialDigest: '${digests.initialDigest}',
} as const;

/** Counts observed by the loader when the registration was produced. */
export const STATIC_WORLD_COUNTS = ${JSON.stringify(loaded.counts, null, 2)} as const;
`, 'utf8');
  console.log(JSON.stringify({ world: basename(worldPath), ...digests, counts: loaded.counts, out }, null, 2));
} finally {
  await server.close();
}
