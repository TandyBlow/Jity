// Independent blind second review for the action-classifier dataset
// (ACTION-DATASET-20261111.md, 03 lane).  A review tool, not a product module
// and not a runner: it never starts a model, never touches the product tree
// and never edits a row.
//
// The official packet from 01 is already the randomized 10% review sample.
// This tool therefore reviews EVERY row in that packet; it does not sample a
// second time (a 10% of a 10% packet would silently review 1%). If 01 sends a
// full dataset instead, `--sample10` is available for development, but the
// official review records which mode was used.
//
// Order is enforced by the tool, not by memory:
//   1. packet-check  X, candidate Y, criterion, source present; no 01
//                    verdicts/reasons; rows not generated by 03; Y uses the
//                    frozen 115 predicates; declared total/sample ratio is
//                    consistent.
//   2. render        only the packet rows for my judgement.
//   3. seal          one pass/fail + one reason for every row; content hash
//                    written before any 01 label is read.
//   4. unblind       refuses without a matching seal, then reports raw
//                    agreement, confusion, class distribution and
//                    skip / 1-step / 2-step splits. Below 85% the floor
//                    breach is reported first.
//
// Usage
//   node scripts/parallel-actions/review-action-dataset.mjs packet-check --packet <file> [--sample10]
//   node scripts/parallel-actions/review-action-dataset.mjs render --packet <file> [--sample10]
//   node scripts/parallel-actions/review-action-dataset.mjs seal --packet <file> --verdicts <jsonl> --out <sealed.json> [--sample10]
//   node scripts/parallel-actions/review-action-dataset.mjs unblind --packet <file> --sealed <file> --labels <01 labels> [--out <agreement.json>]
//   node scripts/parallel-actions/review-action-dataset.mjs --self-test
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const CRITERION_SHA256 = '56092d0c6e5ba0a03e8dc4096e3edb1bb2e4123b351b9f14d6884afdea11d21c';
const SAMPLE_RATE = 0.10;
const AGREEMENT_FLOOR = 0.85;
const NL = String.fromCharCode(10);
const NL_RE = new RegExp(String.fromCharCode(13) + '?' + NL);

const sha256 = (text) => createHash('sha256').update(text, 'utf8').digest('hex');
/** Deep, key-sorted serialization. A top-level key list would silently drop
 * nested keys (seal verdicts, justNow events), weakening the seal and the
 * duplicate-X check. */
function canonical(value) {
  if (Array.isArray(value)) return `[${value.map(canonical).join(',')}]`;
  if (value && typeof value === 'object') {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonical(value[key])}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

/** Keys that would break the blind: 01's verdicts, reasons or review notes. */
const FORBIDDEN_ROW_KEYS = new Set([
  'verdict', 'verdicts', 'pass', 'passed', 'ok', 'label', 'label01',
  'review', 'review01', 'reviewer', 'reviewedat', 'reviewreason', 'issues',
  'passfail', 'judgement01', 'reason01', 'decision01',
]);

/** 01's frozen 115 predicates and their coarse groups. Reading this file is
 * not reading 01's verdicts. */
function loadVocabulary() {
  const url = new URL('../../../../../results/action-dataset-20261111/labels-v1.json', import.meta.url);
  const text = readFileSync(url, 'utf8');
  const data = JSON.parse(text);
  const actionToGroup = new Map();
  for (const group of data.groups ?? []) {
    for (const predicate of group.predicates ?? []) {
      if (actionToGroup.has(predicate)) throw new Error(`predicate ${predicate} appears in two groups`);
      actionToGroup.set(predicate, group.group);
    }
  }
  if (actionToGroup.size !== 115) throw new Error(`vocabulary has ${actionToGroup.size} predicates, expected 115`);
  return { actionToGroup, sha256: sha256(text) };
}

/** The 48 TRAIN goal ids. A row carrying a VALIDATION/TEST goal would leak
 * the held-out split, so it is rejected. */
function loadTrainGoals() {
  const url = new URL('../../../../../results/action-dataset-20261111/01-train-goals-for-13.json', import.meta.url);
  const data = JSON.parse(readFileSync(url, 'utf8'));
  const ids = new Set(data.goalIds ?? []);
  if (ids.size !== (data.count ?? ids.size)) throw new Error(`TRAIN goal list has ${ids.size} ids but count says ${data.count}`);
  if (!ids.size) throw new Error('TRAIN goal list is empty');
  return ids;
}

/** Packets may be a JSON array, a {rows:[...]} object or JSONL. A JSONL packet
 * has no wrapper for metadata; the frozen criterion hash is enforced by this
 * tool regardless. */
function parsePacket(text, file = '') {
  const trimmed = text.trim();
  try {
    return JSON.parse(trimmed);
  } catch (error) {
    const lines = trimmed.split(NL_RE).filter((line) => line.trim());
    if (!file.endsWith('.jsonl') && lines.length < 2) throw error;
    return lines.map((line, index) => {
      try {
        return JSON.parse(line);
      } catch {
        throw new Error(`packet line ${index + 1} is not JSON`);
      }
    });
  }
}

function rowsOf(packet) {
  if (Array.isArray(packet)) return packet;
  if (Array.isArray(packet.rows)) return packet.rows;
  throw new Error('packet must be an array of rows or {rows:[...]}');
}

function stableRowId(row, index) {
  const id = row.rowId ?? row.id;
  if (typeof id !== 'string' || !id.trim()) throw new Error(`row ${index} has no rowId`);
  return id;
}

/** Steps as the row carries them: 0/1/2 entries of {action, object}. */
function stepsOf(row) {
  const steps = row.y?.steps ?? row.y;
  if (!Array.isArray(steps)) throw new Error(`row ${row.rowId} y.steps is not an array`);
  if (steps.length > 2) throw new Error(`row ${row.rowId} has ${steps.length} steps (max 2)`);
  for (const step of steps) {
    if (typeof step?.action !== 'string' || !step.action) {
      throw new Error(`row ${row.rowId} step.action is not a fine-grained predicate`);
    }
  }
  return steps;
}

function classOf(row) {
  const steps = stepsOf(row);
  return steps.length === 0 ? 'skip' : steps.length === 1 ? '1step' : '2step';
}

/** Blind, provenance and Y-shape gates shared by every command. */
export function checkPacket(packet, vocabulary = null, trainGoals = null) {
  const rows = rowsOf(packet);
  const vocab = vocabulary ?? loadVocabulary();
  const train = trainGoals ?? loadTrainGoals();
  const problems = [];
  const warnings = [];
  const rationaleSeen = new Map();
  const xSeen = new Map();
  if (!rows.length) problems.push('packet has no rows');
  const declaredTotal = Number(packet?.totalRows ?? packet?.datasetRows ?? 0);
  const declaredRate = Number(packet?.sampleRate ?? 0);
  if (declaredTotal && declaredRate) {
    const expected = Math.ceil(declaredTotal * declaredRate);
    if (rows.length !== expected) {
      problems.push(`packet has ${rows.length} rows but totalRows ${declaredTotal} x sampleRate ${declaredRate} = ${expected}`);
    }
  } else if (declaredTotal) {
    warnings.push(`packet declares totalRows ${declaredTotal} but no sampleRate; cannot verify the 10% fraction`);
  }
  if (packet?.criterionSha256 && packet.criterionSha256 !== CRITERION_SHA256) {
    problems.push(`criterion sha256 ${packet.criterionSha256} is not the frozen ${CRITERION_SHA256}`);
  }
  if (packet?.vocabularySha256 && packet.vocabularySha256 !== vocab.sha256) {
    problems.push(`packet vocabularySha256 ${packet.vocabularySha256} is not the frozen ${vocab.sha256}`);
  }
  const seen = new Set();
  rows.forEach((row, index) => {
    const id = stableRowId(row, index);
    if (seen.has(id)) problems.push(`duplicate rowId ${id}`);
    seen.add(id);
    const badKeys = Object.keys(row).filter((key) => FORBIDDEN_ROW_KEYS.has(key.toLowerCase())
      || /^01/i.test(key) || /^review/i.test(key));
    if (badKeys.length) problems.push(`row ${id} carries 01-side fields (${badKeys.join(',')}): not blind`);
    for (const field of ['source', 'worldId', 'characterId', 'x', 'yRationale', 'labelSource']) {
      if (row[field] == null) problems.push(`row ${id} is missing ${field}`);
    }
    // 01's actual row shape: x.actor/goals/present/objects/justNow/candidates.
    // The legacy shape is still accepted for old fixtures, but a row that
    // carries x.actor must carry the whole 01 shape.
    if (row.x && typeof row.x === 'object' && row.x.actor != null) {
      if (!row.x.actor.id) problems.push(`row ${id} x.actor has no id`);
      else if (row.x.actor.id !== row.characterId) problems.push(`row ${id} characterId != x.actor.id`);
      for (const field of ['goals', 'present', 'objects', 'candidates']) {
        if (!Array.isArray(row.x[field])) problems.push(`row ${id} x.${field} is not an array`);
      }
      if (row.x.justNow != null && !Array.isArray(row.x.justNow) && typeof row.x.justNow !== 'string') {
        problems.push(`row ${id} x.justNow is neither an event list nor a string`);
      }
      for (const goal of Array.isArray(row.x.goals) ? row.x.goals : []) {
        const goalId = goal?.id;
        if (goalId && !train.has(goalId)) {
          problems.push(`row ${id} goal ${goalId} is not a TRAIN goal (held-out leak)`);
        }
      }
    }
    const rationale = row.yRationale;
    if (typeof rationale === 'string' && rationale.trim()) {
      if (rationaleSeen.has(rationale)) problems.push(`row ${id} yRationale copied from ${rationaleSeen.get(rationale)}`);
      else rationaleSeen.set(rationale, id);
    }
    // A skip must be argued; a non-skip must not carry a skipReason.
    let rowStepsForReason = [];
    try {
      rowStepsForReason = stepsOf(row);
    } catch {
      rowStepsForReason = [];
    }
    if (rowStepsForReason.length === 0) {
      const reason = row.skipReason;
      if (typeof reason !== 'string' || reason.trim().length < 8) {
        problems.push(`row ${id} skip row has no written skipReason`);
      } else {
        for (const banned of ['不知道', '不明', '随便', '无理由', '无关']) {
          if (reason.includes(banned)) problems.push(`row ${id} skipReason uses uninformative wording: ${banned}`);
        }
      }
    } else if (row.skipReason != null) {
      problems.push(`row ${id} non-skip row has a skipReason`);
    }
    // 03 may not review rows it produced or first-labelled.
    for (const field of ['generatedBy', 'constructedBy', 'firstLabeller', 'annotator']) {
      if (typeof row[field] === 'string' && /03|actions/i.test(row[field])) {
        problems.push(`row ${id} was generated/first-labelled by 03 (${field}=${row[field]})`);
      }
    }
    let steps = [];
    try {
      steps = stepsOf(row);
    } catch (error) {
      problems.push(error.message);
    }
    const derivedGroup = steps.length ? (vocab.actionToGroup.get(steps[0].action) ?? null) : 'skip';
    if (derivedGroup && row.yGroup != null) {
      if (typeof row.yGroup === 'string') {
        if (row.yGroup !== derivedGroup) problems.push(`row ${id} yGroup ${row.yGroup} != derived ${derivedGroup}`);
      } else if (Array.isArray(row.yGroup)) {
        if (!row.yGroup.includes(derivedGroup)) problems.push(`row ${id} yGroup ${JSON.stringify(row.yGroup)} does not contain the derived ${derivedGroup}`);
      } else {
        problems.push(`row ${id} yGroup is neither a string nor an array`);
      }
    }
    for (const step of steps) {
      if (!vocab.actionToGroup.get(step.action)) problems.push(`row ${id} step.action ${step.action} is not one of the 115 predicates`);
      if (step.object === row.characterId) problems.push(`row ${id} step.object is the actor`);
    }
    const manifest = packet?.manifest ?? packet?.sourceManifest ?? packet?.sources ?? null;
    if (row.source === 'evidence-snapshot' && !row.sourceRef && !row.evidence && !row.snapshot
      && !(manifest && (manifest[row.rowId] ?? manifest[row.id]))) {
      warnings.push(`row ${id} claims evidence-snapshot but has no source pointer and the packet has no manifest entry`);
    }
    if (row.x && typeof row.x === 'object') {
      const xKey = canonical(row.x);
      if (xSeen.has(xKey)) problems.push(`row ${id} X duplicates ${xSeen.get(xKey)}`);
      else xSeen.set(xKey, id);
    }
    if (typeof row.yRationale === 'string' && row.yRationale.trim().length < 8) {
      problems.push(`row ${id} yRationale is shorter than 8 chars`);
    }
    const ids = new Set((row.x?.candidates ?? []).map((candidate) => candidate?.id ?? candidate));
    for (const step of steps) {
      if (step?.object != null && !ids.has(step.object)) {
        problems.push(`row ${id} step.object ${step.object} is not a candidate id`);
      }
    }
    if (typeof row.yRationale !== 'string' || !row.yRationale.trim()) {
      problems.push(`row ${id} has no yRationale`);
    }
  });
  return { rows, problems, warnings };
}

/** Deterministic 10% pick for a full dataset; official packets use all rows. */
export function sampleRows(packetSha256, rowIds) {
  const ordered = [...rowIds].sort((a, b) => {
    const ha = sha256(`${packetSha256}:${a}`);
    const hb = sha256(`${packetSha256}:${b}`);
    return ha < hb ? -1 : ha > hb ? 1 : a < b ? -1 : a > b ? 1 : 0;
  });
  const k = Math.max(1, Math.ceil(rowIds.length * SAMPLE_RATE));
  return { sampled: ordered.slice(0, k), k, n: rowIds.length, seed: packetSha256 };
}

function reviewRows(packet, text, rows, mode) {
  const ids = rows.map((row, index) => stableRowId(row, index));
  if (mode === 'sample10') return { ids: sampleRows(sha256(text), ids).sampled, mode, reason: 'deterministic 10% of the packet' };
  return { ids, mode: 'packet', reason: 'every row in 01\'s randomized packet (the packet is the 10% sample)' };
}

function readVerdicts(file) {
  const text = readFileSync(file, 'utf8');
  let rows;
  try {
    const data = JSON.parse(text);
    rows = Array.isArray(data) ? data : data.verdicts ?? data.rows ?? [];
  } catch {
    rows = text.split(NL_RE).filter((line) => line.trim()).map((line) => JSON.parse(line));
  }
  if (!Array.isArray(rows)) throw new Error('verdicts file must be JSONL rows or {verdicts:[...]}');
  const byRow = new Map();
  for (const row of rows) {
    const id = row.rowId ?? row.id;
    if (!id) throw new Error('verdict without rowId');
    if (byRow.has(id)) throw new Error(`two verdicts for ${id}`);
    const verdict = String(row.verdict ?? '').toLowerCase();
    if (verdict !== 'pass' && verdict !== 'fail') throw new Error(`verdict for ${id} must be pass|fail`);
    const reason = String(row.reason ?? '').trim();
    if (!reason) throw new Error(`verdict for ${id} has no reason`);
    byRow.set(id, {
      verdict, reason,
      ambiguity: Boolean(row.ambiguity),
      mySteps: Array.isArray(row.mySteps) ? row.mySteps : null,
    });
  }
  return byRow;
}

function readLabels(file) {
  const text = readFileSync(file, 'utf8');
  let data;
  try {
    data = JSON.parse(text);
  } catch {
    data = text.split(NL_RE).filter((line) => line.trim()).map((line) => JSON.parse(line));
  }
  let rows = Array.isArray(data) ? data
    : Array.isArray(data?.rows) ? data.rows
      : Array.isArray(data?.verdicts) ? data.verdicts
        : Array.isArray(data?.labels) ? data.labels : null;
  // 01 may write a map keyed by rowId: { "row-1": {"verdict":"pass",...} }.
  if (!rows && data && typeof data === 'object') {
    const meta = new Set(['version', 'packet', 'packetSha256', 'criterionSha256', 'reviewedAt', 'note', 'labels', 'verdicts', 'rows']);
    rows = Object.entries(data)
      .filter(([key, value]) => !meta.has(key) && (typeof value === 'string' || (value && typeof value === 'object')))
      .map(([key, value]) => (typeof value === 'string' ? { rowId: key, verdict: value } : { rowId: key, ...value }));
  }
  const map = new Map();
  for (const row of rows) {
    const id = row.rowId ?? row.id;
    const value = row.verdict ?? row.pass ?? row.label ?? row.result;
    if (!id || value == null) continue;
    const verdict = value === true ? 'pass' : value === false ? 'fail'
      : /^pass|^ok|^yes/i.test(String(value)) ? 'pass'
        : /^fail|^no/i.test(String(value)) ? 'fail' : null;
    if (!verdict) continue;
    map.set(id, { verdict, reason: row.reason ?? row.rationale ?? null });
  }
  return map;
}

function cmdPacketCheck(file, mode = 'packet') {
  const text = readFileSync(file, 'utf8');
  const packet = parsePacket(text, file);
  const vocabulary = loadVocabulary();
  const { rows, problems, warnings } = checkPacket(packet, vocabulary);
  const review = reviewRows(packet, text, rows, mode);
  const classes = rows.reduce((acc, row) => {
    const key = classOf(row);
    acc[key] = (acc[key] ?? 0) + 1;
    return acc;
  }, {});
  console.log(JSON.stringify({
    packet: file, packetSha256: sha256(text), rows: rows.length,
    criterionSha256: packet?.criterionSha256 ?? null,
    vocabularySha256: vocabulary.sha256,
    declaredTotal: packet?.totalRows ?? null, declaredSampleRate: packet?.sampleRate ?? null,
    classes, reviewRows: review.ids.length, reviewMode: review.mode, reviewReason: review.reason,
    status: problems.length ? 'REJECTED' : 'ACCEPTED',
    problems, warnings,
  }, null, 2));
  return problems.length ? 1 : 0;
}

function cmdRender(file, mode = 'packet') {
  const text = readFileSync(file, 'utf8');
  const packet = parsePacket(text, file);
  const vocabulary = loadVocabulary();
  const { rows, problems } = checkPacket(packet, vocabulary);
  if (problems.length) throw new Error(`packet rejected: ${problems.join('; ')}`);
  const review = reviewRows(packet, text, rows, mode);
  const byId = new Map(rows.map((row, index) => [stableRowId(row, index), row]));
  const blocks = review.ids.map((id, index) => {
    const row = byId.get(id);
    const x = row.x ?? {};
    const steps = stepsOf(row);
    const xText = typeof x === 'string' ? x : '';
    return [
      `### ${index + 1}/${review.ids.length}  rowId=${id}`,
      `source=${row.source} world=${row.worldId} character=${row.characterId} labelSource=${row.labelSource}`,
      row.sourceRef ?? row.evidence ?? row.snapshot ? `sourceRef=${JSON.stringify(row.sourceRef ?? row.evidence ?? row.snapshot)}` : '',
      xText ? `X=${xText}` : '',
      !xText && x.actor ? `X.actor=${x.actor.name ?? ''}(${x.actor.id ?? ''})  精神=${x.actor.sanity ?? ''}  个性=${(x.actor.personality ?? []).join('/')}  位置=${x.actor.location ?? x.actor.position ?? ''}` : '',
      !xText && x.actor ? `X.goals=${(x.goals ?? []).map((g) => `${g?.id}(${g?.text ?? g?.goal ?? g?.description ?? ''})`).join('、') || '（无）'}` : '',
      !xText && !x.actor ? `X.character=${x.character ?? ''}  sanity=${x.sanity ?? ''}  personality=${(x.personality ?? []).join('/')}` : '',
      !xText && !x.actor ? `X.goal=${x.goal ?? ''}` : '',
      !xText ? `X.location=${x.location ?? x.actor?.location ?? x.actor?.position ?? ''}  present=${(x.present ?? []).map((p) => p?.name ?? p).join('、') || '（无）'}` : '',
      !xText ? `X.objects=${(x.objects ?? x.items ?? []).map((p) => p?.name ?? p).join('、') || '（无）'}` : '',
      !xText ? `X.justNow=${Array.isArray(x.justNow)
        ? x.justNow.map((ev) => (typeof ev === 'string' ? ev : ev?.text ?? JSON.stringify(ev))).join(' / ')
        : x.justNow ?? x.justHappened ?? x.recent ?? ''}` : '',
      !xText ? `X.candidates=${(x.candidates ?? []).map((c) => `${c?.id}(${c?.name ?? ''})`).join('、') || '（无）'}` : '',
      !xText && x && typeof x === 'object' ? `X.json=${JSON.stringify(x)}` : '',
      `Y.steps=${JSON.stringify(steps)}`,
      `Y.group=${JSON.stringify(row.yGroup ?? null)}  firstStepGroup=${steps.length ? (vocabulary.actionToGroup.get(steps[0].action) ?? '?') : 'skip'}  Y.rationale=${row.yRationale}`,
      row.skipReason ? `Y.skipReason=${row.skipReason}` : null,
      '',
    ].filter(Boolean).join(NL);
  });
  console.log(`criterion (frozen sha256 ${CRITERION_SHA256}):${NL}${readFileSync(new URL('../../../../../results/action-dataset-20261111/criterion.txt', import.meta.url), 'utf8').trim()}${NL}`);
  const manifest = packet?.manifest ?? packet?.sourceManifest ?? packet?.sources ?? null;
  if (manifest) console.log(`packet source manifest:${NL}${JSON.stringify(manifest, null, 2)}${NL}`);
  console.log(blocks.join(NL));
  return 0;
}

function cmdSeal(packetFile, verdictsFile, outFile, mode = 'packet') {
  const text = readFileSync(packetFile, 'utf8');
  const packet = parsePacket(text, packetFile);
  const vocabulary = loadVocabulary();
  const { rows, problems } = checkPacket(packet, vocabulary);
  if (problems.length) throw new Error(`packet rejected: ${problems.join('; ')}`);
  const packetSha256 = sha256(text);
  const review = reviewRows(packet, text, rows, mode);
  const verdicts = readVerdicts(verdictsFile);
  const missing = review.ids.filter((id) => !verdicts.has(id));
  if (missing.length) throw new Error(`no sealed verdict for ${missing.length}/${review.ids.length}: ${missing.slice(0, 5).join(',')}`);
  const extra = [...verdicts.keys()].filter((id) => !review.ids.includes(id));
  const sealed = {
    lane: '03-actions', role: 'independent blind second reviewer',
    criterionSha256: CRITERION_SHA256, vocabularySha256: vocabulary.sha256,
    packet: packetFile, packetSha256,
    reviewMode: review.mode, reviewReason: review.reason,
    declaredTotal: packet?.totalRows ?? null, declaredSampleRate: packet?.sampleRate ?? null,
    sampledCount: review.ids.length, rowCount: rows.length,
    sealedAt: new Date().toISOString(),
    sawLabels: false,
    verdicts: review.ids.map((id) => ({ rowId: id, ...verdicts.get(id) })),
    unsampledVerdictsIgnored: extra,
  };
  sealed.sealSha256 = sha256(canonical(sealed));
  writeFileSync(outFile, `${JSON.stringify(sealed, null, 2)}${NL}`, 'utf8');
  writeFileSync(`${outFile}.sha256`, `${sealed.sealSha256}  ${outFile}${NL}`, 'utf8');
  console.log(JSON.stringify({
    sealed: outFile, sealSha256: sealed.sealSha256, reviewMode: sealed.reviewMode,
    reviewed: sealed.sampledCount,
    pass: sealed.verdicts.filter((row) => row.verdict === 'pass').length,
    fail: sealed.verdicts.filter((row) => row.verdict === 'fail').length,
    ambiguity: sealed.verdicts.filter((row) => row.ambiguity).length,
  }, null, 2));
  return 0;
}

function cmdUnblind(packetFile, sealedFile, labelsFile, outFile) {
  const sealed = JSON.parse(readFileSync(sealedFile, 'utf8'));
  const text = readFileSync(packetFile, 'utf8');
  const packetSha256 = sha256(text);
  if (sealed.packetSha256 !== packetSha256) throw new Error('sealed file belongs to another packet version');
  if (sealed.criterionSha256 !== CRITERION_SHA256) throw new Error('sealed file used a different criterion');
  const { sealSha256, ...rest } = sealed;
  const actual = sha256(canonical(rest));
  if (actual !== sealSha256) throw new Error('seal hash mismatch: the sealed file changed after sealing');
  const packet = parsePacket(text, packetFile);
  const vocabulary = loadVocabulary();
  const { rows } = checkPacket(packet, vocabulary);
  const byId = new Map(rows.map((row, index) => [stableRowId(row, index), row]));
  const labels = readLabels(labelsFile);
  const compared = sealed.verdicts.filter((row) => labels.has(row.rowId));
  const missing = sealed.verdicts.filter((row) => !labels.has(row.rowId)).map((row) => row.rowId);
  const agree = compared.filter((row) => labels.get(row.rowId).verdict === row.verdict);
  const disagreements = compared.filter((row) => labels.get(row.rowId).verdict !== row.verdict)
    .map((row) => ({
      rowId: row.rowId, mine: row.verdict, mineReason: row.reason,
      theirs: labels.get(row.rowId).verdict, theirsReason: labels.get(row.rowId).reason,
      ambiguity: Boolean(row.ambiguity), class: classOf(byId.get(row.rowId)),
      y: byId.get(row.rowId).y,
    }));
  const byClass = (cls) => {
    const subset = compared.filter((row) => classOf(byId.get(row.rowId)) === cls);
    const same = subset.filter((row) => labels.get(row.rowId).verdict === row.verdict);
    return { n: subset.length, agree: same.length, rate: subset.length ? same.length / subset.length : null };
  };
  const distribution = compared.reduce((acc, row) => {
    const key = classOf(byId.get(row.rowId));
    acc[key] = (acc[key] ?? 0) + 1;
    return acc;
  }, {});
  const report = {
    lane: '03-actions', role: 'independent blind second reviewer',
    criterionSha256: CRITERION_SHA256, vocabularySha256: vocabulary.sha256,
    packetSha256, sealSha256: sealed.sealSha256, sealVerified: actual === sealSha256,
    reviewMode: sealed.reviewMode, declaredTotal: sealed.declaredTotal, declaredSampleRate: sealed.declaredSampleRate,
    sealedAt: sealed.sealedAt, unblindedAt: new Date().toISOString(),
    labelsFile,
    sampled: sealed.verdicts.length, compared: compared.length, missingTheirLabels: missing,
    rawAgreement: compared.length ? agree.length / compared.length : null,
    confusion: {
      bothPass: compared.filter((row) => row.verdict === 'pass' && labels.get(row.rowId).verdict === 'pass').length,
      minePassTheirsFail: compared.filter((row) => row.verdict === 'pass' && labels.get(row.rowId).verdict === 'fail').length,
      mineFailTheirsPass: compared.filter((row) => row.verdict === 'fail' && labels.get(row.rowId).verdict === 'pass').length,
      bothFail: compared.filter((row) => row.verdict === 'fail' && labels.get(row.rowId).verdict === 'fail').length,
    },
    classDistribution: distribution,
    byClass: { skip: byClass('skip'), oneStep: byClass('1step'), twoStep: byClass('2step') },
    ambiguitiesIFlagged: sealed.verdicts.filter((row) => row.ambiguity).map((row) => row.rowId),
    disagreements,
    agreementFloor: AGREEMENT_FLOOR,
    verdict: compared.length && agree.length / compared.length >= AGREEMENT_FLOOR
      ? 'AGREEMENT_AT_OR_ABOVE_FLOOR (does not prove the labels are correct)'
      : 'AGREEMENT_BELOW_FLOOR: report the disagreements first, do not silently edit the criterion',
  };
  const json = `${JSON.stringify(report, null, 2)}${NL}`;
  if (outFile) writeFileSync(outFile, json, 'utf8');
  console.log(json);
  return 0;
}

function selfTest() {
  const criterion = readFileSync(new URL('../../../../../results/action-dataset-20261111/criterion.txt', import.meta.url), 'utf8');
  if (sha256(criterion) !== CRITERION_SHA256) throw new Error('criterion file hash drifted');

  const row = (id, steps, extra = {}) => ({
    rowId: id, source: 'constructed', worldId: 'w1', characterId: 'c1', labelSource: 'builder-judgment',
    x: {
      actor: { id: 'c1', name: '甲', sanity: 50, personality: [], location: '巷口' },
      goals: [{ id: 'task_caesar_bridge', text: '到钟楼' }],
      present: [], objects: [{ id: 'door', name: '门' }], justNow: [{ text: `无（${id}）` }],
      candidates: [{ id: 'door', name: '门' }],
    },
    y: { steps },
    yGroup: steps.length ? (steps[0].action === '观察' ? '感知' : '移动') : 'skip',
    yRationale: `去钟楼要先出门（${id}）`,
    skipReason: steps.length ? null : '当前没有可执行的下一步',
    ...extra,
  });
  const expectProblem = (packet, fragment, label) => {
    if (!checkPacket(packet).problems.some((problem) => problem.includes(fragment))) {
      throw new Error(`${label} not caught`);
    }
  };

  // 1. Schema, classes, vocabulary and every rejection gate.
  const good = { criterionSha256: CRITERION_SHA256, rows: [row('r1', []), row('r2', [{ action: '移动', object: null }])] };
  if (checkPacket(good).problems.length) throw new Error(`valid packet rejected: ${checkPacket(good).problems.join('; ')}`);
  if (classOf({ rowId: 'x', y: { steps: [] } }) !== 'skip') throw new Error('skip class wrong');
  if (classOf({ rowId: 'x', y: { steps: [{ action: '移动' }, { action: '观察' }] } }) !== '2step') throw new Error('2step class wrong');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [row('r1', [], { verdict: 'pass' })] }, 'not blind', 'verdict leak');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [row('r1', [], { reviewNote: 'ok' })] }, 'not blind', 'review field leak');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [row('r1', [], { generatedBy: '03-actions' })] }, 'generated/first-labelled', 'own row');
  expectProblem({ criterionSha256: 'deadbeef', rows: [row('r1', [])] }, 'not the frozen', 'criterion drift');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [row('r1', [{ action: '观察', object: 'nope' }])] }, 'not a candidate id', 'unknown object');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [row('r1', [{ action: '飞升', object: null }])] }, 'not one of the 115', 'predicate outside the vocabulary');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [row('r1', [{ action: '移动', object: null }], { yGroup: ['战斗'] })] }, 'does not contain the derived', 'yGroup mismatch');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [row('r1', [{ action: '移动', object: null }])], vocabularySha256: 'deadbeef' }, 'vocabularySha256', 'vocabulary drift');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [{ ...row('r1', []), characterId: 'other' }] }, 'characterId != x.actor.id', 'actor mismatch');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [row('r1', [], { x: { ...row('r1', []).x, goals: [{ id: 'task_heldout_test' }] } })] }, 'not a TRAIN goal', 'held-out goal leak');
  const evidence = checkPacket({ criterionSha256: CRITERION_SHA256, rows: [row('r1', [], { source: 'evidence-snapshot' })] });
  if (!evidence.warnings.some((warning) => warning.includes('no source pointer'))) throw new Error('missing evidence pointer not warned');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [row('r1', [], { skipReason: null })] }, 'skip row has no written skipReason', 'skip without reason');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [row('r1', [], { x: { ...row('r1', []).x, justNow: 42 } })] }, 'justNow is neither', 'bad justNow type');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [row('r1', [{ action: '移动', object: null }], { skipReason: '有理由' })] }, 'non-skip row has a skipReason', 'non-skip with skipReason');
  expectProblem({ criterionSha256: CRITERION_SHA256, rows: [row('r1', []), row('r2', [], { yRationale: '去钟楼要先出门（r1）' })] }, 'yRationale copied', 'copied rationale');

  // 2. Packet is the 10% sample: review every row, never a 10% of 10%.
  const packet30 = { totalRows: 300, sampleRate: 0.1, criterionSha256: CRITERION_SHA256,
    rows: Array.from({ length: 30 }, (_, index) => row(`p${index}`, index % 2 ? [] : [{ action: '移动', object: null }])) };
  const reviewed = reviewRows(packet30, 'packet-text', rowsOf(packet30), 'packet');
  if (reviewed.ids.length !== 30) throw new Error('packet mode must review every row (30), not a sample');
  if (checkPacket(packet30).problems.length) throw new Error(`valid 30/300 packet rejected: ${checkPacket(packet30).problems.join('; ')}`);
  expectProblem({ ...packet30, rows: packet30.rows.slice(0, 5) }, 'totalRows 300 x sampleRate 0.1 = 30', 'wrong packet fraction');

  // 3. Optional --sample10 is deterministic and exactly 10% when a full set is given.
  const ids = Array.from({ length: 30 }, (_, index) => `r${index}`);
  const a = sampleRows('abc', ids);
  const b = sampleRows('abc', ids);
  if (a.k !== 3 || JSON.stringify(a.sampled) !== JSON.stringify(b.sampled)) throw new Error('sampling not deterministic 10%');
  if (JSON.stringify(sampleRows('abd', ids).sampled) === JSON.stringify(a.sampled)) throw new Error('sampling ignores the packet seed');

  // 4. JSONL packet parsing.
  const jsonl = [row('j1', []), row('j2', [{ action: '移动', object: null }])]
    .map((entry) => JSON.stringify(entry)).join(NL);
  const parsed = parsePacket(jsonl, 'packet.jsonl');
  if (!Array.isArray(parsed) || parsed.length !== 2) throw new Error('JSONL packet not parsed');
  if (checkPacket(parsed).problems.length) throw new Error(`valid JSONL packet rejected: ${checkPacket(parsed).problems.join('; ')}`);

  // 5. Seal refuses a partial verdict set, accepts a complete one, hashes content.
  const dir = mkdtempSync(join(tmpdir(), 'action-review-'));
  const at = (name) => join(dir, name);
  try {
    const packet = { criterionSha256: CRITERION_SHA256, rows: Array.from({ length: 40 }, (_, index) => row(`s${index}`, index % 3 === 0 ? [] : [{ action: '移动', object: null }])) };
    writeFileSync(at('packet.json'), JSON.stringify(packet, null, 2));
    const packetText = readFileSync(at('packet.json'), 'utf8');
    const sampled = rowsOf(packet).map((entry) => entry.rowId);
    writeFileSync(at('partial.jsonl'), `${JSON.stringify({ rowId: sampled[0], verdict: 'pass', reason: 'ok' })}${NL}`);
    let refused = false;
    try {
      cmdSeal(at('packet.json'), at('partial.jsonl'), at('sealed-bad.json'));
    } catch {
      refused = true;
    }
    if (!refused) throw new Error('seal accepted a partial verdict set');
    writeFileSync(at('verdicts.jsonl'), sampled.map((id) => JSON.stringify({ rowId: id, verdict: 'pass', reason: '符合判据' })).join(NL));
    capture(() => cmdSeal(at('packet.json'), at('verdicts.jsonl'), at('sealed.json')));
    const sealedObj = JSON.parse(readFileSync(at('sealed.json'), 'utf8'));
    if (sealedObj.sampledCount !== sampled.length) throw new Error('seal did not cover the sample');
    if (sealedObj.packetSha256 !== sha256(packetText)) throw new Error('seal did not pin the packet');
    if (sealedObj.reviewMode !== 'packet') throw new Error('seal must record the review mode');

    // 6. Agreement math, seal verification and the no-seal/no-wrong-packet gates.
    // 10 of 40 differ -> 0.75, below the 0.85 floor.
    writeFileSync(at('labels.json'), JSON.stringify({ rows: sampled.map((id, index) => ({ rowId: id, verdict: index % 4 === 0 ? 'fail' : 'pass' })) }));
    const report = JSON.parse(capture(() => cmdUnblind(at('packet.json'), at('sealed.json'), at('labels.json'), null)));
    if (Math.abs(report.rawAgreement - 0.75) > 1e-9) throw new Error(`agreement ${report.rawAgreement} wrong`);
    if (report.confusion.minePassTheirsFail !== 10) throw new Error('confusion matrix wrong');
    if (!report.sealVerified) throw new Error('seal hash not verified');
    if (!report.verdict.includes('BELOW_FLOOR')) throw new Error('a sub-floor agreement must be reported as below floor');
    writeFileSync(at('labels-all.json'), JSON.stringify({ rows: sampled.map((id) => ({ rowId: id, verdict: 'pass' })) }));
    const high = JSON.parse(capture(() => cmdUnblind(at('packet.json'), at('sealed.json'), at('labels-all.json'), null)));
    if (high.rawAgreement !== 1) throw new Error('agreement 1.0 expected');
    if (!high.verdict.includes('does not prove')) throw new Error('agreement must not be presented as correctness proof');
    let noSeal = false;
    try {
      cmdUnblind(at('packet.json'), at('missing.json'), at('labels.json'), null);
    } catch {
      noSeal = true;
    }
    if (!noSeal) throw new Error('unblind ran without a seal');
    const tampered = JSON.parse(readFileSync(at('sealed.json'), 'utf8'));
    tampered.verdicts[0].verdict = 'fail';
    writeFileSync(at('sealed-tampered.json'), JSON.stringify(tampered));
    let tamperRefused = false;
    try {
      cmdUnblind(at('packet.json'), at('sealed-tampered.json'), at('labels.json'), null);
    } catch {
      tamperRefused = true;
    }
    if (!tamperRefused) throw new Error('tampered seal was accepted');
    writeFileSync(at('labels-map.json'), JSON.stringify({ [sampled[0]]: { verdict: 'pass', reason: 'map form' } }));
    const mapped = readLabels(at('labels-map.json'));
    if (mapped.get(sampled[0])?.verdict !== 'pass') throw new Error('rowId-keyed labels map not parsed');
    writeFileSync(at('packet2.json'), JSON.stringify({ ...packet, note: 'v2' }));
    let wrongPacket = false;
    try {
      cmdUnblind(at('packet2.json'), at('sealed.json'), at('labels.json'), null);
    } catch {
      wrongPacket = true;
    }
    if (!wrongPacket) throw new Error('seal from another packet version was accepted');
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
  console.log(`self-test passed: blind/provenance/vocabulary gates, packet-is-10% all-row review, declared-fraction check, deterministic optional 10%, JSONL, complete-verdict seal, agreement math, no seal / wrong packet refused`);
}

function capture(fn) {
  const original = console.log;
  let out = '';
  console.log = (...args) => { out += args.join(' '); };
  try {
    fn();
  } finally {
    console.log = original;
  }
  return out;
}

const [, , command, ...rest] = process.argv;
const flag = (name) => {
  const index = rest.indexOf(`--${name}`);
  return index >= 0 ? rest[index + 1] : undefined;
};
const mode = rest.includes('--sample10') ? 'sample10' : 'packet';

try {
  if (command === '--self-test') selfTest();
  else if (command === 'packet-check') process.exitCode = cmdPacketCheck(flag('packet'), mode);
  else if (command === 'render') process.exitCode = cmdRender(flag('packet'), mode);
  else if (command === 'seal') process.exitCode = cmdSeal(flag('packet'), flag('verdicts'), flag('out'), mode);
  else if (command === 'unblind') process.exitCode = cmdUnblind(flag('packet'), flag('sealed'), flag('labels'), flag('out'));
  else {
    console.error('usage: packet-check|render|seal|unblind --packet <file> ... (or --self-test)');
    process.exitCode = 2;
  }
} catch (error) {
  console.error(`error: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
}
